// Cloudflare Worker entry for the GridIQ web app.
//
// /api/* goes to the GridIQ server (API_ORIGIN, a Worker variable set in the
// Cloudflare dashboard, e.g. https://api.example.co.za, behind a Cloudflare
// Tunnel to Caddy). Everything else is the Next.js app built by
// @opennextjs/cloudflare. The browser stays on one origin, so the auth
// service's HttpOnly, SameSite=Strict session cookie works unchanged.
//
// Excluded from the Next.js type check (tsconfig "exclude"): it imports the
// adapter's build output, which exists only after `opennextjs-cloudflare build`.

// @ts-ignore: generated by opennextjs-cloudflare build
import { default as nextHandler } from "./.open-next/worker.js";

interface Env { API_ORIGIN?: string }

/** Hop-by-hop headers are not forwarded. */
const HOP = ["connection", "keep-alive", "proxy-authenticate", "proxy-authorization", "te", "trailer", "transfer-encoding", "upgrade", "host"];

export async function proxyApi(request: Request, origin: string): Promise<Response> {
    const url = new URL(request.url);
    const target = new URL(url.pathname + url.search, origin);
    const headers = new Headers(request.headers);
    for (const h of HOP) headers.delete(h);
    headers.set("x-forwarded-host", url.host);
    headers.set("x-forwarded-proto", url.protocol.replace(":", ""));
    const hasBody = request.method !== "GET" && request.method !== "HEAD";
    const upstream = await fetch(target.toString(), {
        method: request.method,
        headers,
        body: hasBody ? request.body : undefined,
        redirect: "manual",
    });
    // Pass the answer through untouched (status, Set-Cookie, streamed body).
    return new Response(upstream.body, { status: upstream.status, statusText: upstream.statusText, headers: upstream.headers });
}

export default {
    async fetch(request: Request, env: Env, ctx: unknown): Promise<Response> {
        const { pathname } = new URL(request.url);
        if (pathname === "/api" || pathname.startsWith("/api/")) {
            const origin = (env.API_ORIGIN ?? "").replace(/\/$/, "");
            if (!/^https?:\/\//.test(origin)) {
                return new Response(JSON.stringify({ error: "API_ORIGIN is not configured on this Worker" }), {
                    status: 503, headers: { "content-type": "application/json" },
                });
            }
            try {
                return await proxyApi(request, origin);
            } catch (e) {
                return new Response(JSON.stringify({ error: "The GridIQ server is not reachable" }), {
                    status: 502, headers: { "content-type": "application/json" },
                });
            }
        }
        return nextHandler.fetch(request, env, ctx);
    },
};
