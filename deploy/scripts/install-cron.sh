#!/usr/bin/env bash
# Install Grid-IQ's scheduled jobs on the server (Oracle VM, plan Part D10).
#
#   sudo bash deploy/scripts/install-cron.sh
#
# Writes /etc/cron.d/gridiq (re-running replaces it) and a logrotate config:
#   02:00 daily     backup.sh            (SAST)
#   03:30 daily     sync-mqtt-certs.sh   (copies Caddy's renewed MQTT cert, restarts mosquitto only if changed)
#   04:00 Sunday    restore-drill.sh
#   05:00 Sunday    docker cleanup: stopped containers, dangling images and build cache
#                   older than 7 days. Never `-a` (previous image tags are what
#                   deploy/rollback.sh rolls back to) and never volumes.
# Times are the server's local time: plan Part D2 sets Africa/Johannesburg.
set -euo pipefail

if [ "$(id -u)" != 0 ]; then echo "install-cron: run with sudo" >&2; exit 1; fi
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

TZ_NOW="$(timedatectl show -p Timezone --value 2>/dev/null || cat /etc/timezone 2>/dev/null || echo unknown)"
if [ "$TZ_NOW" != Africa/Johannesburg ]; then
    echo "install-cron: WARNING: server timezone is $TZ_NOW, not Africa/Johannesburg; the times below are in $TZ_NOW." >&2
    echo "              Fix with: sudo timedatectl set-timezone Africa/Johannesburg" >&2
fi

mkdir -p /var/log/gridiq
cat > /etc/cron.d/gridiq <<EOF
# Grid-IQ scheduled jobs — generated by deploy/scripts/install-cron.sh; edit that, not this.
SHELL=/bin/bash
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin

0 2 * * *   root  cd $REPO_DIR && bash deploy/scripts/backup.sh          >> /var/log/gridiq/backup.log 2>&1
30 3 * * *  root  cd $REPO_DIR && bash deploy/scripts/sync-mqtt-certs.sh >> /var/log/gridiq/certs.log 2>&1
0 4 * * 0   root  cd $REPO_DIR && bash deploy/scripts/restore-drill.sh   >> /var/log/gridiq/restore-drill.log 2>&1
0 5 * * 0   root  { docker container prune -f --filter "until=168h"; docker image prune -f; docker builder prune -f --filter "until=168h"; } >> /var/log/gridiq/prune.log 2>&1
EOF
chmod 0644 /etc/cron.d/gridiq

cat > /etc/logrotate.d/gridiq <<'EOF'
/var/log/gridiq/*.log {
    weekly
    rotate 8
    compress
    missingok
    notifempty
}
EOF

echo "install-cron: installed /etc/cron.d/gridiq and /etc/logrotate.d/gridiq"
cat /etc/cron.d/gridiq
