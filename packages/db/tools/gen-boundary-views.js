#!/usr/bin/env node
'use strict';
// Generates migrations/<ts>_boundary-attribution.sql from the aggregate and
// fleet-model migrations, so the boundary views use exactly the same
// formulas as the continuous aggregates they stand in for.
//
//   node packages/db/tools/gen-boundary-views.js > packages/db/migrations/<ts>_boundary-attribution.sql
//
// The problem it fixes: point_readings_* gave a whole bucket to the
// deployment that held its first sample (t_first). A minute, hour or day that
// straddles a move was therefore attributed wholesale to one client.
//
// deployment_readings_<w> holds, per deployment:
//   - interior buckets (entirely inside [installed_at, removed_at)) straight
//     from readings_<w>;
//   - boundary buckets recomputed from only the samples inside the window:
//     1m from raw meter_readings, coarser ones from deployment_readings_1m with
//     the aggregate's own (hierarchical) formulas.
// point_readings_<w> keeps its columns and corrections, reading from these.

const fs = require('node:fs');
const path = require('node:path');

const MIG = path.join(__dirname, '..', 'migrations');
const agg = fs.readFileSync(path.join(MIG, '1793778295849_aggregates-and-alerting.sql'), 'utf8').replace(/\r\n/g, '\n');
const fleet = fs.readFileSync(path.join(MIG, '1793798165302_fleet-model.sql'), 'utf8').replace(/\r\n/g, '\n');

const WIDTHS = { '1m': '1 minute', '10m': '10 minutes', '30m': '30 minutes', '1h': '1 hour', '1d': '1 day' };

/** The select-list lines of a continuous aggregate, without meter_id and bucket. */
function caSelect(name) {
    const m = agg.match(new RegExp(`CREATE MATERIALIZED VIEW ${name}\\n[^\\n]*\\nSELECT\\n([\\s\\S]*?)\\nFROM (\\w+)\\n`));
    if (!m) throw new Error(`aggregate ${name} not found`);
    const lines = m[1].split('\n')
        .filter((l) => !/^\s*--/.test(l))
        .filter((l) => !/^\s*meter_id,\s*$/.test(l))
        .filter((l) => !/AS bucket,\s*$/.test(l));
    const body = lines.join('\n').replace(/,\s*$/, '');
    const cols = [...body.matchAll(/ AS (\w+)\s*(,|$)/gm)].map((x) => x[1]);
    return { body, cols, from: m[2] };
}

/** A point view's projection (the SELECT list) from the fleet migration. */
function pointProjection(w) {
    const m = fleet.match(new RegExp(`CREATE VIEW point_readings_${w} AS\\nSELECT ([\\s\\S]*?)\\nFROM readings_${w} r\\n`));
    if (!m) throw new Error(`point_readings_${w} not found`);
    return m[1]
        .replace('d.measurement_point_id,', 'r.measurement_point_id,')
        .replace('d.id AS deployment_id,', 'r.deployment_id,');
}

const out = [];
out.push(`-- Up Migration
-- Boundary-correct attribution (GridIQ assessment model, section 4).
-- GENERATED by packages/db/tools/gen-boundary-views.js from the aggregate and
-- fleet-model migrations; edit the generator, not this file.
--
-- Before: a bucket went to the deployment holding its first sample, so a
-- minute/hour/day that straddled a move went wholesale to one client.
-- Now: deployment_readings_<w> takes interior buckets from readings_<w> and
-- recomputes the (at most two) boundary buckets per deployment from only the
-- samples inside [installed_at, removed_at). point_readings_<w> keep their
-- columns and corrections and read from them. Raw readings are untouched.
`);

const r1 = caSelect('readings_1m');
const interiorCols = (cols) => cols.map((c) => `       r.${c}`).join(',\n');

out.push(`CREATE VIEW deployment_readings_1m AS
SELECT d.id AS deployment_id,
       d.measurement_point_id,
       r.meter_id,
       r.bucket,
${interiorCols(r1.cols)}
FROM readings_1m r
JOIN deployments d ON d.device_id = r.meter_id
                  AND r.bucket >= d.installed_at
                  AND (d.removed_at IS NULL OR r.bucket + INTERVAL '1 minute' <= d.removed_at)
UNION ALL
SELECT d.id AS deployment_id,
       d.measurement_point_id,
       d.device_id AS meter_id,
       b.bk AS bucket,
${r1.body}
FROM deployments d
CROSS JOIN LATERAL (
    SELECT DISTINCT x AS bk FROM unnest(ARRAY[
        CASE WHEN time_bucket('1 minute', d.installed_at) < d.installed_at THEN time_bucket('1 minute', d.installed_at) END,
        CASE WHEN time_bucket('1 minute', d.removed_at) < d.removed_at THEN time_bucket('1 minute', d.removed_at) END
    ]) AS x WHERE x IS NOT NULL) b
JOIN meter_readings mr ON mr.meter_id = d.device_id
                      AND mr.time >= GREATEST(b.bk, d.installed_at)
                      AND mr.time < LEAST(b.bk + INTERVAL '1 minute', COALESCE(d.removed_at, 'infinity'::timestamptz))
GROUP BY d.id, d.measurement_point_id, d.device_id, b.bk;
`);

for (const w of ['10m', '30m', '1h', '1d']) {
    const ca = caSelect(`readings_${w}`);
    const width = WIDTHS[w];
    out.push(`CREATE VIEW deployment_readings_${w} AS
SELECT d.id AS deployment_id,
       d.measurement_point_id,
       r.meter_id,
       r.bucket,
${interiorCols(ca.cols)}
FROM readings_${w} r
JOIN deployments d ON d.device_id = r.meter_id
                  AND r.bucket >= d.installed_at
                  AND (d.removed_at IS NULL OR r.bucket + INTERVAL '${width}' <= d.removed_at)
UNION ALL
SELECT d.id AS deployment_id,
       d.measurement_point_id,
       d.device_id AS meter_id,
       b.bk AS bucket,
${ca.body.replace(/\bbucket\b(?!_)/g, 'x.bucket').replace(/\bAS x\.bucket\b/g, 'AS bucket')}
FROM deployments d
CROSS JOIN LATERAL (
    SELECT DISTINCT y AS bk FROM unnest(ARRAY[
        CASE WHEN time_bucket('${width}', d.installed_at) < d.installed_at THEN time_bucket('${width}', d.installed_at) END,
        CASE WHEN time_bucket('${width}', d.removed_at) < d.removed_at THEN time_bucket('${width}', d.removed_at) END
    ]) AS y WHERE y IS NOT NULL) b
JOIN deployment_readings_1m x ON x.deployment_id = d.id
                             AND x.measurement_point_id = d.measurement_point_id
                             AND x.bucket >= b.bk AND x.bucket < b.bk + INTERVAL '${width}'
GROUP BY d.id, d.measurement_point_id, d.device_id, b.bk;
`);
}

for (const w of ['1m', '10m', '30m', '1h', '1d']) {
    out.push(`CREATE OR REPLACE VIEW point_readings_${w} AS
SELECT ${pointProjection(w)}
FROM deployment_readings_${w} r
JOIN deployments d ON d.id = r.deployment_id
JOIN measurement_points p ON p.id = r.measurement_point_id
JOIN projects pr ON pr.id = p.project_id;
`);
}

// Down: restore the t_first attribution exactly as the fleet migration had it.
out.push('-- Down Migration');
for (const w of ['1m', '10m', '30m', '1h', '1d']) {
    const m = fleet.match(new RegExp(`(CREATE VIEW point_readings_${w} AS\\n[\\s\\S]*?JOIN projects pr ON pr.id = p.project_id;)`));
    out.push(m[1].replace('CREATE VIEW', 'CREATE OR REPLACE VIEW') + '\n');
}
for (const w of ['1d', '1h', '30m', '10m', '1m']) out.push(`DROP VIEW deployment_readings_${w};`);

process.stdout.write(out.join('\n') + '\n');
